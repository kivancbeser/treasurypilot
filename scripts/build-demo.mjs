import { mkdir, readFile, writeFile, copyFile, rm } from 'node:fs/promises';
const output = new URL('../dist/', import.meta.url);
await rm(output, { recursive: true, force: true });
await mkdir(new URL('src/', output), { recursive: true });
let html = await readFile(new URL('../index.html', import.meta.url), 'utf8');
html = html.replace('<a href="/beta">Team beta · Sign in</a>', '<a href="https://github.com/kivancbeser/treasurypilot" target="_blank" rel="noopener noreferrer">Source code ↗</a>');
html = html.replace('Interactive prototype · Simulated USD accounting', 'Public interactive demo · Simulated USD accounting');
await writeFile(new URL('index.html', output), html);
for (const file of ['style.css', 'src/app.js', 'src/treasury.js']) await copyFile(new URL('../' + file, import.meta.url), new URL(file, output));
console.log('Built static demo in dist/. No accounts, backend, or local records included.');
